import React, { useMemo, useState } from 'react';
import {
  Sparkles,
  Check,
  Layers,
  Plus,
  Trash2,
  X,
  ArrowRight,
  Search,
  CheckCircle2,
  Wand2,
} from 'lucide-react';
import { LeadRecord, MergeableField, MergeRule, SemanticSuggestion } from '../types/dashboard';

interface SmartMergeModalProps {
  isOpen: boolean;
  leads: LeadRecord[];
  rules: MergeRule[];
  suggestions: SemanticSuggestion[];
  onApplyRule: (rule: MergeRule) => void;
  onApplyAllSuggestions: (suggestions: SemanticSuggestion[]) => void;
  onRemoveRule: (ruleId: string) => void;
  onClearAllRules: () => void;
  onClose: () => void;
}

export const SmartMergeModal: React.FC<SmartMergeModalProps> = ({
  isOpen,
  leads,
  rules,
  suggestions,
  onApplyRule,
  onApplyAllSuggestions,
  onRemoveRule,
  onClearAllRules,
  onClose,
}) => {
  const [activeField, setActiveField] = useState<MergeableField>('industria');
  const [selectedValues, setSelectedValues] = useState<string[]>([]);
  const [targetCategoryName, setTargetCategoryName] = useState('');
  const [searchValue, setSearchValue] = useState('');
  const [editableSuggestions, setEditableSuggestions] = useState<Record<string, string>>({});

  // Compute unique values and counts for the active field
  const valueCounts = useMemo(() => {
    const map = new Map<string, { current: string; originalVariants: Set<string>; count: number }>();
    for (const lead of leads) {
      const val =
        activeField === 'industria'
          ? lead.industria
          : activeField === 'cargo'
          ? lead.cargo
          : lead.pais;
      const orig =
        activeField === 'industria'
          ? lead.industriaOriginal
          : activeField === 'cargo'
          ? lead.cargoOriginal
          : lead.pais;

      const entry = map.get(val) ?? { current: val, originalVariants: new Set<string>(), count: 0 };
      entry.count += 1;
      entry.originalVariants.add(orig);
      map.set(val, entry);
    }
    return Array.from(map.values()).sort((a, b) => b.count - a.count);
  }, [leads, activeField]);

  if (!isOpen) return null;

  const filteredSuggestions = suggestions.filter((s) => s.field === activeField);
  const filteredValues = valueCounts.filter((item) =>
    item.current.toLowerCase().includes(searchValue.toLowerCase())
  );

  const toggleSelectValue = (val: string) => {
    setSelectedValues((prev) =>
      prev.includes(val) ? prev.filter((v) => v !== val) : [...prev, val]
    );
  };

  const handleCreateManualMerge = (e: React.FormEvent) => {
    e.preventDefault();
    if (selectedValues.length === 0 || !targetCategoryName.trim()) return;

    // Collect all underlying original values that map to the selected values
    const underlyingOriginals = new Set<string>();
    selectedValues.forEach((v) => underlyingOriginals.add(v));
    for (const lead of leads) {
      const currentVal =
        activeField === 'industria'
          ? lead.industria
          : activeField === 'cargo'
          ? lead.cargo
          : lead.pais;
      const origVal =
        activeField === 'industria'
          ? lead.industriaOriginal
          : activeField === 'cargo'
          ? lead.cargoOriginal
          : lead.pais;
      if (selectedValues.includes(currentVal)) {
        underlyingOriginals.add(origVal);
      }
    }

    onApplyRule({
      id: `manual-${activeField}-${Date.now()}`,
      field: activeField,
      targetCategory: targetCategoryName.trim(),
      sourceValues: Array.from(underlyingOriginals),
      autoGenerated: false,
    });

    setSelectedValues([]);
    setTargetCategoryName('');
  };

  const handleAcceptSingleSuggestion = (sug: SemanticSuggestion) => {
    const customTarget = (editableSuggestions[sug.id] ?? sug.suggestedCategory).trim();
    if (!customTarget) return;

    onApplyRule({
      id: `auto-${sug.id}-${Date.now()}`,
      field: sug.field,
      targetCategory: customTarget,
      sourceValues: sug.matchedValues.map((m) => m.value),
      autoGenerated: true,
    });
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/50 backdrop-blur-sm flex items-center justify-center p-4 overflow-y-auto">
      <div className="bg-white rounded-3xl border border-slate-200 shadow-2xl max-w-5xl w-full overflow-hidden my-8 flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="px-6 py-5 bg-gradient-to-r from-indigo-950 via-slate-900 to-blue-950 text-white flex items-center justify-between shrink-0">
          <div className="flex items-center gap-3.5">
            <div className="w-11 h-11 rounded-2xl bg-indigo-500/20 border border-indigo-400/30 flex items-center justify-center">
              <Sparkles className="w-5 h-5 text-indigo-300" />
            </div>
            <div>
              <div className="flex items-center gap-2.5">
                <h2 className="text-lg font-bold">Módulo de Integridad y Normalización (Smart Merge)</h2>
                <span className="px-2.5 py-0.5 rounded-full text-xs font-semibold bg-indigo-500/20 text-indigo-200 border border-indigo-400/30">
                  Fuzzy Matching + Consolidación Manual
                </span>
              </div>
              <p className="text-xs text-slate-300 mt-0.5">
                Unifica variaciones semánticas o bilingües (ej. &ldquo;banking&rdquo; y &ldquo;banca&rdquo;, o tipos de &ldquo;manufactura&rdquo;) antes de generar los reportes.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl bg-white/10 hover:bg-white/20 text-slate-200 transition-colors cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Dimension Switcher Bar */}
        <div className="px-6 py-3 bg-slate-100/80 border-b border-slate-200 flex flex-wrap items-center justify-between gap-3 shrink-0">
          <div className="flex items-center gap-2">
            {(
              [
                { id: 'industria', label: 'Industrias / Sectores' },
                { id: 'cargo', label: 'Cargos / Roles Ejecutivos' },
                { id: 'pais', label: 'Países / Regiones' },
              ] as const
            ).map((tab) => {
              const tabSugCount = suggestions.filter((s) => s.field === tab.id).length;
              return (
                <button
                  key={tab.id}
                  onClick={() => {
                    setActiveField(tab.id);
                    setSelectedValues([]);
                  }}
                  className={`inline-flex items-center gap-2 px-4 py-2 rounded-xl text-xs font-bold transition-all cursor-pointer ${
                    activeField === tab.id
                      ? 'bg-white text-indigo-600 shadow-sm border border-slate-200/80'
                      : 'text-slate-600 hover:bg-white/60'
                  }`}
                >
                  <span>{tab.label}</span>
                  {tabSugCount > 0 && (
                    <span className="px-1.5 py-0.2 rounded-full text-[10px] bg-amber-100 text-amber-800 border border-amber-300">
                      {tabSugCount}
                    </span>
                  )}
                </button>
              );
            })}
          </div>

          {suggestions.length > 0 && (
            <button
              onClick={() => onApplyAllSuggestions(suggestions)}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold shadow-sm transition-all cursor-pointer"
            >
              <Wand2 className="w-3.5 h-3.5" />
              <span>Unificar Todas las Sugerencias Semánticas ({suggestions.length})</span>
            </button>
          )}
        </div>

        {/* Main Body: 2 Columns (Left: Semantic Suggestions & Active Rules, Right: Manual Multi-Select Merge) */}
        <div className="p-6 overflow-y-auto grid grid-cols-1 lg:grid-cols-12 gap-6 flex-1 bg-slate-50/50">
          {/* Left Column (7 cols): Semantic Fuzzy Matching & Active Consolidation Rules */}
          <div className="lg:col-span-7 space-y-5">
            {/* Section 1: Semantic / Fuzzy Suggestions */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-4 shadow-sm">
              <div className="flex items-center justify-between mb-3">
                <div className="flex items-center gap-2">
                  <Sparkles className="w-4 h-4 text-amber-500" />
                  <h3 className="text-sm font-bold text-slate-900">
                    1. Agrupación Semántica Automática (Fuzzy Matching)
                  </h3>
                </div>
                <span className="text-xs font-medium text-slate-500">
                  {filteredSuggestions.length} grupos detectados
                </span>
              </div>

              {filteredSuggestions.length === 0 ? (
                <div className="p-6 rounded-xl bg-emerald-50/60 border border-emerald-200/70 text-center">
                  <CheckCircle2 className="w-7 h-7 text-emerald-600 mx-auto mb-1.5" />
                  <p className="text-xs font-bold text-emerald-900">
                    ¡Categorías de {activeField} normalizadas!
                  </p>
                  <p className="text-[11px] text-emerald-700 mt-0.5">
                    No se detectaron más variaciones duplicadas o bilingües pendientes en esta dimensión.
                  </p>
                </div>
              ) : (
                <div className="space-y-3">
                  {filteredSuggestions.map((sug) => {
                    const currentTarget = editableSuggestions[sug.id] ?? sug.suggestedCategory;
                    return (
                      <div
                        key={sug.id}
                        className="p-3.5 rounded-xl bg-indigo-50/40 border border-indigo-200/80 flex flex-col gap-2.5"
                      >
                        <div className="flex items-start justify-between gap-2">
                          <div>
                            <span className="text-[11px] font-semibold text-indigo-700 block">
                              {sug.reason}
                            </span>
                            <div className="flex flex-wrap items-center gap-1.5 mt-1.5">
                              {sug.matchedValues.map((m) => (
                                <span
                                  key={m.value}
                                  className="inline-flex items-center gap-1 px-2 py-0.5 rounded-lg text-xs font-medium bg-white text-slate-700 border border-slate-200 shadow-2xs"
                                >
                                  <span>&ldquo;{m.value}&rdquo;</span>
                                  <span className="text-[10px] font-bold text-slate-400">({m.count})</span>
                                </span>
                              ))}
                            </div>
                          </div>
                        </div>

                        <div className="flex flex-wrap items-center gap-2 pt-2 border-t border-indigo-100">
                          <span className="text-xs font-semibold text-slate-600">Unificar bajo:</span>
                          <input
                            type="text"
                            value={currentTarget}
                            onChange={(e) =>
                              setEditableSuggestions((prev) => ({ ...prev, [sug.id]: e.target.value }))
                            }
                            className="flex-1 min-w-[180px] px-3 py-1.5 rounded-lg bg-white border border-indigo-300 text-xs font-bold text-slate-900 focus:outline-none focus:ring-2 focus:ring-indigo-500/20"
                          />
                          <button
                            onClick={() => handleAcceptSingleSuggestion(sug)}
                            className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold transition-colors cursor-pointer"
                          >
                            <Check className="w-3.5 h-3.5" />
                            <span>Agrupar</span>
                          </button>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>

            {/* Section 2: Active Consolidation Rules */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-4 shadow-sm">
              <div className="flex items-center justify-between mb-3">
                <div className="flex items-center gap-2">
                  <Layers className="w-4 h-4 text-blue-600" />
                  <h3 className="text-sm font-bold text-slate-900">
                    Reglas de Consolidación Activas ({rules.length})
                  </h3>
                </div>
                {rules.length > 0 && (
                  <button
                    onClick={onClearAllRules}
                    className="text-xs font-semibold text-rose-600 hover:underline cursor-pointer"
                  >
                    Restaurar valores originales
                  </button>
                )}
              </div>

              {rules.length === 0 ? (
                <p className="text-xs text-slate-500 py-3">
                  Aún no has aplicado reglas de consolidación. Acepta una sugerencia arriba o selecciona valores manualmente a la derecha.
                </p>
              ) : (
                <div className="space-y-2 max-h-56 overflow-y-auto pr-1">
                  {rules.map((r) => (
                    <div
                      key={r.id}
                      className="flex items-center justify-between gap-2 p-2.5 rounded-xl bg-slate-50 border border-slate-200/80 text-xs"
                    >
                      <div className="min-w-0 flex-1">
                        <div className="flex items-center gap-2">
                          <span className="px-2 py-0.5 rounded text-[10px] font-bold uppercase bg-blue-100 text-blue-800">
                            {r.field}
                          </span>
                          <span className="font-bold text-slate-900">{r.targetCategory}</span>
                        </div>
                        <p className="text-[11px] text-slate-500 truncate mt-1">
                          Agrupa: {r.sourceValues.map((v) => `"${v}"`).join(', ')}
                        </p>
                      </div>
                      <button
                        onClick={() => onRemoveRule(r.id)}
                        title="Eliminar regla"
                        className="p-1.5 rounded-lg text-slate-400 hover:text-rose-600 hover:bg-rose-50 transition-colors cursor-pointer"
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                      </button>
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>

          {/* Right Column (5 cols): Manual Multi-Select Merge */}
          <div className="lg:col-span-5 bg-white rounded-2xl border border-slate-200/90 p-4 shadow-sm flex flex-col">
            <h3 className="text-sm font-bold text-slate-900 mb-1">
              2. Merge Manual / Reglas Personalizadas
            </h3>
            <p className="text-xs text-slate-500 mb-3">
              Selecciona múltiples valores de <strong>{activeField}</strong> y asígnales una categoría principal unificada.
            </p>

            {/* Search inside unique values */}
            <div className="relative mb-3">
              <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                value={searchValue}
                onChange={(e) => setSearchValue(e.target.value)}
                placeholder={`Filtrar valores de ${activeField}...`}
                className="w-full pl-8 pr-3 py-2 rounded-xl bg-slate-50 border border-slate-200 text-xs focus:outline-none focus:border-blue-500"
              />
            </div>

            {/* Multi-select list */}
            <div className="flex-1 max-h-64 overflow-y-auto space-y-1.5 pr-1 mb-4 border border-slate-100 rounded-xl p-2 bg-slate-50/50">
              {filteredValues.map((item) => {
                const isSelected = selectedValues.includes(item.current);
                const variantsList = Array.from(item.originalVariants);
                const wasMerged =
                  variantsList.length > 1 ||
                  (variantsList.length === 1 && variantsList[0] !== item.current);

                return (
                  <label
                    key={item.current}
                    className={`flex items-center justify-between gap-2 p-2.5 rounded-xl border text-xs cursor-pointer transition-all select-none ${
                      isSelected
                        ? 'bg-blue-50/90 border-blue-400 text-blue-950 font-semibold'
                        : 'bg-white border-slate-200/70 text-slate-700 hover:bg-slate-50'
                    }`}
                  >
                    <div className="flex items-center gap-2.5 min-w-0">
                      <input
                        type="checkbox"
                        checked={isSelected}
                        onChange={() => toggleSelectValue(item.current)}
                        className="rounded text-blue-600 focus:ring-blue-500"
                      />
                      <div className="truncate">
                        <span className="block truncate">{item.current}</span>
                        {wasMerged && (
                          <span className="block text-[10px] text-indigo-600 font-normal truncate">
                            Incluye: {variantsList.join(', ')}
                          </span>
                        )}
                      </div>
                    </div>
                    <span className="px-2 py-0.5 rounded-full text-[11px] font-bold bg-slate-100 text-slate-700 shrink-0">
                      {item.count} reg.
                    </span>
                  </label>
                );
              })}
            </div>

            {/* Target category input & Submit */}
            <form onSubmit={handleCreateManualMerge} className="mt-auto pt-3 border-t border-slate-200 space-y-2.5">
              <div className="flex items-center justify-between text-xs">
                <span className="font-semibold text-slate-600">
                  Valores seleccionados: <strong className="text-blue-600">{selectedValues.length}</strong>
                </span>
                {selectedValues.length > 0 && (
                  <button
                    type="button"
                    onClick={() => setSelectedValues([])}
                    className="text-[11px] text-slate-400 hover:text-slate-600 cursor-pointer"
                  >
                    Desmarcar
                  </button>
                )}
              </div>

              <input
                type="text"
                value={targetCategoryName}
                onChange={(e) => setTargetCategoryName(e.target.value)}
                placeholder="Ej: Manufactura, Banca / Servicios Financieros..."
                className="w-full px-3.5 py-2.5 rounded-xl border border-slate-300 text-xs font-semibold text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-600"
              />

              <button
                type="submit"
                disabled={selectedValues.length === 0 || !targetCategoryName.trim()}
                className="w-full inline-flex items-center justify-center gap-1.5 px-4 py-2.5 rounded-xl bg-slate-900 hover:bg-slate-800 disabled:bg-slate-200 disabled:text-slate-400 text-white text-xs font-bold transition-all cursor-pointer disabled:cursor-not-allowed"
              >
                <Plus className="w-4 h-4" />
                <span>Unificar {selectedValues.length > 0 ? `(${selectedValues.length})` : ''} en Categoría Principal</span>
              </button>
            </form>
          </div>
        </div>

        {/* Footer */}
        <div className="px-6 py-4 bg-white border-t border-slate-200 flex items-center justify-between shrink-0">
          <div className="text-xs text-slate-500">
            Los gráficos de <strong>Industrias</strong>, <strong>Cargos</strong> y <strong>Países</strong> se actualizan en tiempo real con estas reglas.
          </div>
          <button
            onClick={onClose}
            className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold shadow-md shadow-blue-500/20 transition-all cursor-pointer"
          >
            <span>Ir al Dashboard Analítico</span>
            <ArrowRight className="w-4 h-4" />
          </button>
        </div>
      </div>
    </div>
  );
};
