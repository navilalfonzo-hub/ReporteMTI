export type QualificationStatus = 'Calificada' | 'Descalificada' | 'Pendiente';

export interface LeadRecord {
  id: string;
  empresa: string;
  pais: string;
  industriaOriginal: string;
  industria: string;
  cargoOriginal: string;
  cargo: string;
  campana: string;
  fechaEjecucion: string; // YYYY-MM-DD
  aceptado: boolean;
  respondio: boolean;
  interesado: boolean;
  fechaInteres: string; // YYYY-MM-DD or ''
  reunionAgendada: boolean;
  fechaReunion: string; // YYYY-MM-DD or ''
  calificacion: QualificationStatus;
  feedback: string;
}

export interface ColumnMapping {
  empresa: string;
  pais: string;
  industria: string;
  cargo: string;
  campana: string;
  fechaEjecucion: string;
  aceptado: string;
  respondio: string;
  interesado: string;
  fechaInteres: string;
  reunionAgendada: string;
  fechaReunion: string;
  calificacion: string;
  feedback: string;
}

export type MergeableField = 'industria' | 'cargo' | 'pais';

export interface MergeRule {
  id: string;
  field: MergeableField;
  targetCategory: string;
  sourceValues: string[];
  autoGenerated?: boolean;
}

export interface SemanticSuggestion {
  id: string;
  field: MergeableField;
  suggestedCategory: string;
  matchedValues: { value: string; count: number }[];
  reason: string;
}

export interface GlobalFilterState {
  datePreset: 'all' | 'last30' | 'quarter' | 'month' | 'custom';
  startDate: string;
  endDate: string;
  comparePreviousPeriod: boolean;
  selectedCountry: string;
  selectedIndustry: string;
  selectedRole: string;
  selectedCampaign: string;
  searchQuery: string;
}

export interface KPIMetric {
  id: string;
  label: string;
  rate: number; // Percentage 0..100
  numerator: number;
  denominator: number;
  numeratorLabel: string;
  denominatorLabel: string;
  previousRate: number;
  deltaPercent: number; // e.g., +14.2 or -5.1
  sparkline: number[];
}

